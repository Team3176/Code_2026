    private turretSolution calculateGoalLocationFromTag(PhotonTrackedTarget target) {
        // This method will return the distance (in M) and angle (in Rad) to the target
        // if it sees one of the "goal-center" April Tags
        // It Takes a "target"
        // It returns [distance,angleToTarget]

        int[] redGoalTagList = { 5, 10, 2 };
        int[] blueGoalTagList = { 21, 26, 18 };
        boolean thisTargetIsAGoal = false;

        // Initialize something to return
        turretSolution aTurretSolution = new turretSolution();

        int targetID = target.getFiducialId();
        int displayIndex = 0; // The index of the diplay vector 0 for left, 1 for center, 2 for right;

        if (target.poseAmbiguity > 0.2) { // If the pose ambiguity is bad, throw out the value and return an invalid
                                          // solutoin (high ambiguiity is bad)
            aTurretSolution.IsValid = false;
            return aTurretSolution;
        }

        if (weAreBlueAlliance) {
            // if we are the blue alliance alliance, calculate the goal location from the
            // target data
            if (targetID == 21 || targetID == 26 || targetID == 18) { // Check to make sure that the targetID is one of
                                                                      // the blue goal targets
                turretGoodLock = true;
                thisTargetIsAGoal = true;
                switch (targetID) {
                    case 21:
                        displayIndex = 0;
                        break;

                    case 26:
                        displayIndex = 1;
                        break;
                    case 18:
                        displayIndex = 2;
                        break;

                    default:

                }
            }

        } else {
            // If we are the red alliance
            if (targetID == 5 || targetID == 10 || targetID == 2) { // Check to make sure that the TargetID id one of
                                                                    // the red goal targets
                turretGoodLock = true;
                thisTargetIsAGoal = true;
                switch (targetID) {
                    case 5:
                        displayIndex = 0;
                        break;

                    case 10:
                        displayIndex = 1;
                        break;
                    case 2:
                        displayIndex = 2;
                        break;

                    default:

                }

            }

            if (thisTargetIsAGoal) {
                double x = target.getBestCameraToTarget().getX();
                double y = target.getBestCameraToTarget().getY();
                double z = target.getBestCameraToTarget().getRotation().getZ() + 3.141593;

                double alpha = Math.atan(y / x);
                double d = Math.sqrt(x * x + y * y);

                double beta = z - alpha;

                double Xg = d * Math.cos(alpha) + 0.5931 * Math.cos(alpha + beta);
                double Yg = d * Math.sin(alpha) + 0.5931 * Math.sin(alpha + beta);

                double thetaG = Math.atan(Yg / Xg);
                double distG = Math.sqrt(Xg * Xg + Yg * Yg);

                turretDistancesTogoal[displayIndex] = distG;
                turretAnglesToGoal[displayIndex] = thetaG;

                turretXGoal[displayIndex] = Xg;
                turretYGoal[displayIndex] = Yg;

                aTurretSolution.IsValid = true;
                aTurretSolution.angle = thetaG;
                aTurretSolution.distance = distG;

            }

        }

        return aTurretSolution;

    }
